export function serializeReportDefinition(definition) {
  return {
    id: definition.id,
    displayName: definition.displayName,
    description: definition.description,
    filename: definition.filename,
    dimensions: definition.dimensions.map((dimension) => typeof dimension === "string" ? dimension : dimension.output || dimension.name),
    requestDimensions: definition.dimensions.map((dimension) => typeof dimension === "string" ? dimension : dimension.name),
    metrics: definition.metrics.map((metric) => typeof metric === "string" ? metric : metric.output || metric.name),
    requestMetrics: definition.metrics.map((metric) => typeof metric === "string" ? metric : metric.name),
    ordering: definition.ordering,
    filters: definition.filters,
    optional: definition.optional,
    category: definition.category,
    dashboardVisibility: definition.dashboardVisibility,
  };
}
